// @ts-check
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import crypto from "node:crypto";

/**
 * Courses live as plain JSON under ~/.masterly (or $MASTERLY_HOME):
 *
 *   config.json                 model settings
 *   courses/<id>/course.json    sources, concepts, questions, review state, history
 *   courses/<id>/passages.json  the text of the material, split into passages
 *
 * Writes are atomic (write to a temp file, then rename), so a crash never leaves a
 * half-written course.
 *
 * @typedef {object} Source
 * @property {string} id
 * @property {string} file
 * @property {string} title
 * @property {string} type
 * @property {number} chars
 * @property {string} sha256
 * @property {number} addedAt
 *
 * @typedef {object} Concept
 * @property {string} id
 * @property {string} name
 * @property {string} summary
 * @property {string[]} prereqs
 * @property {import("./ground.js").VerifiedEvidence[]} evidence
 * @property {number} order
 *
 * @typedef {object} Question
 * @property {string} id
 * @property {string} concept
 * @property {"mcq"|"tf"|"short"} type
 * @property {string} prompt
 * @property {string[]} [options]
 * @property {number|boolean|string} answer   option index, true/false, or model answer
 * @property {string[]} [keyPoints]
 * @property {string} explanation
 * @property {import("./ground.js").VerifiedEvidence[]} evidence
 *
 * @typedef {object} Review
 * @property {string} q
 * @property {string} c
 * @property {number} at
 * @property {1|2|3|4} rating
 * @property {number} score    0..1
 * @property {string} [answer]
 *
 * @typedef {object} Course
 * @property {number} version
 * @property {string} id
 * @property {string} name
 * @property {number} createdAt
 * @property {string} [language]
 * @property {Source[]} sources
 * @property {Concept[]} concepts
 * @property {Question[]} questions
 * @property {Record<string, import("./fsrs.js").Card>} cards
 * @property {Review[]} log
 * @property {{status: "empty"|"ready"|"building"|"built"|"failed", at?: number, model?: string, message?: string, rejected?: {concepts: number, questions: number}, calls?: number}} build
 * @property {{retention: number, newPerDay: number, questionsPerConcept: number, maxConcepts: number}} settings
 */

export function home() {
  return process.env.MASTERLY_HOME || path.join(os.homedir(), ".masterly");
}

function coursesDir() {
  return path.join(home(), "courses");
}

/** @param {string} file @param {unknown} value */
export function writeJson(file, value) {
  fs.mkdirSync(path.dirname(file), { recursive: true, mode: 0o700 });
  const tmp = `${file}.${process.pid}.${crypto.randomBytes(4).toString("hex")}.tmp`;
  fs.writeFileSync(tmp, JSON.stringify(value), { mode: 0o600 });
  fs.renameSync(tmp, file);
}

/** @param {string} file @param {any} fallback */
export function readJson(file, fallback) {
  try {
    return JSON.parse(fs.readFileSync(file, "utf8"));
  } catch (e) {
    if (/** @type {any} */ (e).code === "ENOENT") return fallback;
    throw new Error(`cannot read ${file}: ${/** @type {Error} */ (e).message}`);
  }
}

/** Course ids are generated by masterly; refuse anything else so ids can't escape the folder. @param {string} id */
function safeId(id) {
  if (!/^[a-z0-9][a-z0-9-]{0,63}$/.test(id)) throw new Error(`invalid course id "${id}"`);
  return id;
}

/** @param {string} name */
export function slug(name) {
  const s = name
    .normalize("NFKD")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 40);
  return `${s || "course"}-${crypto.randomBytes(3).toString("hex")}`;
}

/** @param {string} name @returns {Course} */
export function createCourse(name) {
  const clean = String(name || "").trim().slice(0, 120) || "Untitled course";
  /** @type {Course} */
  const course = {
    version: 1,
    id: slug(clean),
    name: clean,
    createdAt: Date.now(),
    sources: [],
    concepts: [],
    questions: [],
    cards: {},
    log: [],
    build: { status: "empty" },
    settings: { retention: 0.9, newPerDay: 15, questionsPerConcept: 3, maxConcepts: 40 },
  };
  saveCourse(course, { create: true });
  savePassages(course.id, []);
  return course;
}

export class CourseGone extends Error {}

/**
 * Save a course. Refuses to recreate a course whose folder was deleted (for example
 * by the user while a build was still running).
 * @param {Course} course @param {{create?: boolean}} [opts]
 */
export function saveCourse(course, opts = {}) {
  const dir = path.join(coursesDir(), safeId(course.id));
  if (!opts.create && !fs.existsSync(dir)) throw new CourseGone(`course "${course.name}" was deleted`);
  writeJson(path.join(dir, "course.json"), course);
}

/**
 * Re-read the course, apply a change, save. Use this whenever time has passed since the
 * course was loaded, so concurrent changes (a review during a build) are not lost.
 * @param {string} id @param {(c: Course) => void} change
 * @returns {Course}
 */
export function updateCourse(id, change) {
  const c = loadCourse(id);
  if (!c) throw new CourseGone("course was deleted");
  change(c);
  saveCourse(c);
  return c;
}

/** @param {string} id @returns {Course | null} */
export function loadCourse(id) {
  return readJson(path.join(coursesDir(), safeId(id), "course.json"), null);
}

/** @param {string} id @returns {import("./chunk.js").Passage[]} */
export function loadPassages(id) {
  return readJson(path.join(coursesDir(), safeId(id), "passages.json"), []);
}

/** @param {string} id @param {import("./chunk.js").Passage[]} passages */
export function savePassages(id, passages) {
  writeJson(path.join(coursesDir(), safeId(id), "passages.json"), passages);
}

/** @returns {Course[]} */
export function listCourses() {
  let names = [];
  try {
    names = fs.readdirSync(coursesDir());
  } catch {
    return [];
  }
  return names
    .filter((n) => /^[a-z0-9][a-z0-9-]{0,63}$/.test(n))
    .map((n) => loadCourse(n))
    .filter((c) => c !== null)
    .sort((a, b) => b.createdAt - a.createdAt);
}

/** @param {string} id */
export function deleteCourse(id) {
  fs.rmSync(path.join(coursesDir(), safeId(id)), { recursive: true, force: true });
}

/** Find a course by id or by (unique, case-insensitive) name or id prefix. @param {string} ref */
export function findCourse(ref) {
  const all = listCourses();
  const exact = all.find((c) => c.id === ref);
  if (exact) return exact;
  const matches = all.filter((c) => c.name.toLowerCase() === ref.toLowerCase() || c.id.startsWith(ref.toLowerCase()));
  if (matches.length === 1) return matches[0];
  if (matches.length > 1) throw new Error(`"${ref}" matches several courses: ${matches.map((c) => c.id).join(", ")}`);
  return null;
}

export function configFile() {
  return path.join(home(), "config.json");
}

/** @returns {{baseUrl?: string, apiKey?: string, model?: string}} */
export function loadSettings() {
  return readJson(configFile(), {});
}

/** @param {{baseUrl?: string, apiKey?: string, model?: string}} s */
export function saveSettings(s) {
  writeJson(configFile(), s);
}
