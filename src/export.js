// @ts-check
import { loadPassages } from "./store.js";
import { placeOf } from "./chunk.js";

/**
 * Exports: an Anki-importable TSV of every question, and a Markdown study guide of the
 * concepts in learning order with their source quotes.
 */

/** @param {string} s */
function cell(s) {
  return String(s).replace(/\t/g, " ").replace(/\r?\n/g, "<br>");
}

/** @param {string} s */
function html(s) {
  return String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

/** @param {import("./store.js").Course} course */
export function ankiTsv(course) {
  const passages = new Map(loadPassages(course.id).map((p) => [p.id, p]));
  const titles = new Map(course.sources.map((s) => [s.id, s.title]));
  const concepts = new Map(course.concepts.map((c) => [c.id, c]));
  const lines = ["#separator:tab", "#html:true", "#columns:Front\tBack\tTags"];
  for (const q of course.questions) {
    let front = html(q.prompt);
    let back = "";
    if (q.type === "mcq") {
      front += "<br><br>" + (q.options || []).map((o, i) => `${String.fromCharCode(65 + i)}. ${html(o)}`).join("<br>");
      back = `<b>${String.fromCharCode(65 + Number(q.answer))}. ${html((q.options || [])[Number(q.answer)] || "")}</b>`;
    } else if (q.type === "tf") {
      front = `True or false? ${front}`;
      back = `<b>${q.answer ? "True" : "False"}</b>`;
    } else {
      back = `<b>${html(String(q.answer))}</b>`;
      if (q.keyPoints?.length) back += `<ul>${q.keyPoints.map((k) => `<li>${html(k)}</li>`).join("")}</ul>`;
    }
    if (q.explanation) back += `<br>${html(q.explanation)}`;
    for (const e of q.evidence) {
      const p = passages.get(e.chunk);
      back += `<br><br><i>“${html(e.excerpt)}”</i> (${html(p ? placeOf(titles.get(p.source) || "", p.label) : e.chunk)})`;
    }
    const tag = (concepts.get(q.concept)?.name || "concept").replace(/[^\p{L}\p{N}]+/gu, "_");
    lines.push(`${cell(front)}\t${cell(back)}\tmasterly ${tag}`);
  }
  return lines.join("\n") + "\n";
}

/** @param {import("./store.js").Course} course */
export function studyGuide(course) {
  const passages = new Map(loadPassages(course.id).map((p) => [p.id, p]));
  const titles = new Map(course.sources.map((s) => [s.id, s.title]));
  const names = new Map(course.concepts.map((c) => [c.id, c.name]));
  let md = `# ${course.name}\n\nStudy guide generated by masterly from: ${course.sources.map((s) => s.title).join(", ")}.\nConcepts are in learning order: each one comes after the concepts it builds on.\n`;
  for (const c of [...course.concepts].sort((a, b) => a.order - b.order)) {
    md += `\n## ${c.order + 1}. ${c.name}\n\n${c.summary}\n`;
    if (c.prereqs.length) md += `\nBuilds on: ${c.prereqs.map((p) => names.get(p) || p).join(", ")}\n`;
    for (const e of c.evidence.slice(0, 3)) {
      const p = passages.get(e.chunk);
      md += `\n> ${e.excerpt.replace(/\n+/g, " ")}\n>\n> (${p ? placeOf(titles.get(p.source) || "", p.label) : e.chunk})\n`;
    }
  }
  return md;
}
